-- Meridian Bank digital onboarding: decision tier schema (portable SQL; runs on Postgres and, for tests, H2 in PostgreSQL mode)

CREATE TABLE branch (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)  NOT NULL UNIQUE,
    name            VARCHAR(120) NOT NULL,
    region          VARCHAR(60)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE staff_user (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id        VARCHAR(20)  NOT NULL UNIQUE,
    full_name          VARCHAR(120) NOT NULL,
    role_name          VARCHAR(32)  NOT NULL,
    home_branch_id     BIGINT REFERENCES branch (id),
    max_approval_tier  VARCHAR(16)  NOT NULL DEFAULT 'tier_0',
    status             VARCHAR(16)  NOT NULL DEFAULT 'active',
    created_at         TIMESTAMP    NOT NULL
);

CREATE TABLE user_account (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                    VARCHAR(255) NOT NULL UNIQUE,
    password_hash            VARCHAR(100),
    role_name                VARCHAR(32)  NOT NULL,
    status                   VARCHAR(16)  NOT NULL,
    staff_id                 BIGINT REFERENCES staff_user (id),
    failed_login_count       INT          NOT NULL DEFAULT 0,
    locked_until             TIMESTAMP,
    registration_token_hash  VARCHAR(64),
    email_verified_at        TIMESTAMP,
    mobile_verified_at       TIMESTAMP,
    created_at               TIMESTAMP    NOT NULL,
    last_login_at            TIMESTAMP
);

CREATE TABLE applicant (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id         BIGINT REFERENCES user_account (id),
    full_name               VARCHAR(120),
    date_of_birth           DATE,
    national_identifier     VARCHAR(40),
    email                   VARCHAR(255),
    mobile                  VARCHAR(30),
    address_line1           VARCHAR(160),
    address_line2           VARCHAR(160),
    city                    VARCHAR(80),
    postal_code             VARCHAR(12),
    country                 VARCHAR(60),
    employment_status       VARCHAR(24),
    employer_name           VARCHAR(160),
    declared_annual_income  NUMERIC(19,2),
    created_at              TIMESTAMP NOT NULL,
    updated_at              TIMESTAMP
);

CREATE TABLE onb_application (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                VARCHAR(24) NOT NULL UNIQUE,
    applicant_id             BIGINT      NOT NULL REFERENCES applicant (id),
    status                   VARCHAR(32) NOT NULL,
    current_step             VARCHAR(32) NOT NULL,
    branch_id                BIGINT REFERENCES branch (id),
    assigned_officer_id      BIGINT REFERENCES staff_user (id),
    derived_kyc_tier         VARCHAR(16) NOT NULL DEFAULT 'tier_0',
    overridden_kyc_tier      VARCHAR(16),
    decision_outcome         VARCHAR(16),
    customer_visible_reason  TEXT,
    internal_reason          TEXT,
    requested_document_types TEXT,
    requested_message        TEXT,
    requested_at             TIMESTAMP,
    screening_due_at         TIMESTAMP,
    screening_attempts       INT NOT NULL DEFAULT 0,
    screening_error          TEXT,
    submitted_at             TIMESTAMP,
    decided_at               TIMESTAMP,
    last_activity_at         TIMESTAMP,
    created_at               TIMESTAMP NOT NULL
);

CREATE TABLE journey_step (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL REFERENCES onb_application (id),
    step_key       VARCHAR(32) NOT NULL,
    completed      BOOLEAN     NOT NULL DEFAULT FALSE,
    completed_at   TIMESTAMP,
    captured_data  TEXT,
    UNIQUE (application_id, step_key)
);

CREATE TABLE document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT       NOT NULL REFERENCES onb_application (id),
    doc_type            VARCHAR(32)  NOT NULL,
    category            VARCHAR(16)  NOT NULL,
    original_filename   VARCHAR(255) NOT NULL,
    storage_name        VARCHAR(100) NOT NULL UNIQUE,
    content_type        VARCHAR(80)  NOT NULL,
    size_bytes          BIGINT       NOT NULL,
    uploaded_by         BIGINT REFERENCES user_account (id),
    verification_state  VARCHAR(16)  NOT NULL,
    verified_by         BIGINT REFERENCES staff_user (id),
    verified_at         TIMESTAMP,
    expiry_date         TIMESTAMP,
    rekyc_case_id       BIGINT,
    created_at          TIMESTAMP    NOT NULL
);

CREATE TABLE document_requirement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kyc_tier       VARCHAR(16) NOT NULL,
    doc_type       VARCHAR(32) NOT NULL,
    condition_type VARCHAR(32),
    UNIQUE (kyc_tier, doc_type, condition_type)
);

CREATE TABLE kyc_tier_policy (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tier_code               VARCHAR(16)  NOT NULL UNIQUE,
    display_name            VARCHAR(80)  NOT NULL,
    min_identity_match      INT          NOT NULL,
    daily_transaction_limit NUMERIC(19,2) NOT NULL,
    balance_ceiling         NUMERIC(19,2) NOT NULL,
    currency                VARCHAR(3)   NOT NULL
);

CREATE TABLE identity_verification_result (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id     BIGINT       NOT NULL REFERENCES onb_application (id),
    provider_reference VARCHAR(80),
    match_score        INT,
    outcome            VARCHAR(24),
    raw_xml            TEXT,
    status             VARCHAR(16)  NOT NULL,
    error_message      VARCHAR(255),
    created_at         TIMESTAMP    NOT NULL
);

CREATE TABLE bureau_result (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL REFERENCES onb_application (id),
    score          INT,
    liabilities    TEXT,
    status         VARCHAR(16) NOT NULL,
    pulled_at      TIMESTAMP   NOT NULL
);

CREATE TABLE watchlist_hit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT        NOT NULL REFERENCES onb_application (id),
    matched_name   VARCHAR(160)  NOT NULL,
    list_source    VARCHAR(80)   NOT NULL,
    confidence     NUMERIC(5,2)  NOT NULL,
    disposition    VARCHAR(16)   NOT NULL,
    disposed_by    BIGINT REFERENCES staff_user (id),
    disposed_at    TIMESTAMP,
    justification  TEXT,
    created_at     TIMESTAMP     NOT NULL
);

CREATE TABLE otp_challenge (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id  BIGINT REFERENCES user_account (id),
    purpose          VARCHAR(32) NOT NULL,
    channel          VARCHAR(16) NOT NULL,
    code_hash        VARCHAR(64) NOT NULL,
    session_ref_hash VARCHAR(64) NOT NULL,
    issued_at        TIMESTAMP   NOT NULL,
    expires_at       TIMESTAMP   NOT NULL,
    attempt_count    INT         NOT NULL DEFAULT 0,
    consumed_at      TIMESTAMP
);

CREATE TABLE step_up_grant (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT      NOT NULL REFERENCES user_account (id),
    purpose        VARCHAR(32) NOT NULL,
    session_id     VARCHAR(64) NOT NULL,
    expires_at     TIMESTAMP   NOT NULL,
    created_at     TIMESTAMP   NOT NULL
);

CREATE TABLE password_reset_token (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT      NOT NULL REFERENCES user_account (id),
    token_hash     VARCHAR(64) NOT NULL UNIQUE,
    expires_at     TIMESTAMP   NOT NULL,
    consumed_at    TIMESTAMP,
    created_at     TIMESTAMP   NOT NULL
);

CREATE TABLE auth_session (
    id             VARCHAR(64) PRIMARY KEY,
    user_account_id BIGINT      NOT NULL REFERENCES user_account (id),
    issued_at      TIMESTAMP   NOT NULL,
    expires_at     TIMESTAMP   NOT NULL,
    revoked_at     TIMESTAMP
);

CREATE TABLE account (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL UNIQUE REFERENCES onb_application (id),
    account_number VARCHAR(24) NOT NULL UNIQUE,
    product        VARCHAR(80) NOT NULL,
    kyc_tier       VARCHAR(16) NOT NULL,
    core_reference VARCHAR(60) NOT NULL,
    status         VARCHAR(16) NOT NULL,
    opened_at      TIMESTAMP   NOT NULL
);

CREATE TABLE rekyc_campaign (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(160) NOT NULL,
    target_segment  VARCHAR(120),
    target_kyc_tier VARCHAR(16),
    due_days        INT          NOT NULL,
    created_by      BIGINT REFERENCES staff_user (id),
    created_at      TIMESTAMP    NOT NULL
);

CREATE TABLE rekyc_case (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      BIGINT REFERENCES rekyc_campaign (id),
    origin           VARCHAR(16) NOT NULL,
    customer_user_id BIGINT      NOT NULL REFERENCES user_account (id),
    application_id   BIGINT      NOT NULL REFERENCES onb_application (id),
    status           VARCHAR(16) NOT NULL,
    due_date         TIMESTAMP,
    started_at       TIMESTAMP,
    completed_at     TIMESTAMP,
    created_at       TIMESTAMP   NOT NULL
);

ALTER TABLE document ADD CONSTRAINT fk_document_rekyc_case FOREIGN KEY (rekyc_case_id) REFERENCES rekyc_case (id);

CREATE TABLE notification (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_account_id BIGINT      NOT NULL REFERENCES user_account (id),
    type           VARCHAR(32) NOT NULL,
    title          VARCHAR(160) NOT NULL,
    body           TEXT        NOT NULL,
    link           VARCHAR(255),
    is_read        BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMP   NOT NULL
);

CREATE TABLE outbox_email (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient VARCHAR(255) NOT NULL,
    subject   VARCHAR(255) NOT NULL,
    body      TEXT         NOT NULL,
    purpose   VARCHAR(40),
    status    VARCHAR(16)  NOT NULL,
    created_at TIMESTAMP   NOT NULL,
    sent_at   TIMESTAMP
);

CREATE TABLE audit_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type          VARCHAR(16) NOT NULL,
    actor               VARCHAR(160) NOT NULL,
    actor_id            BIGINT,
    action              VARCHAR(80) NOT NULL,
    entity_type         VARCHAR(60) NOT NULL,
    entity_id           VARCHAR(60),
    before_value        TEXT,
    after_value         TEXT,
    authorization_basis VARCHAR(120),
    created_at          TIMESTAMP  NOT NULL
);

CREATE TABLE webhook_setting (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_url VARCHAR(500),
    secret       VARCHAR(200),
    enabled      BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at   TIMESTAMP
);

CREATE TABLE webhook_delivery (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(60) NOT NULL,
    payload       TEXT        NOT NULL,
    response_code INT,
    success       BOOLEAN     NOT NULL,
    error         TEXT,
    attempted_at  TIMESTAMP   NOT NULL
);

CREATE INDEX idx_application_status ON onb_application (status);
CREATE INDEX idx_application_branch ON onb_application (branch_id);
CREATE INDEX idx_document_app ON document (application_id);
CREATE INDEX idx_document_state ON document (verification_state);
CREATE INDEX idx_hit_app ON watchlist_hit (application_id);
CREATE INDEX idx_notification_user ON notification (user_account_id, is_read);
CREATE INDEX idx_audit_created ON audit_event (created_at);
CREATE INDEX idx_audit_entity ON audit_event (entity_type, entity_id);
